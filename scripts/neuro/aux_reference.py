#!/usr/bin/env python3
"""N24 - the NORMATIVE Python reference renderer (spec §4, integers only)
and the parity-vector generator for the Rust port.

Every calculation here is pure integer arithmetic on masked fixed-point
fields — the same contract the Rust `aux::render` module must satisfy
bit-for-bit. This script, run with --vectors, prints Rust test constants:

    python3 scripts/neuro/aux_reference.py --vectors > src/aux/test_vectors.rs.part
"""

import argparse
import hashlib
import math
import struct

TABLE_N = 16384
PHASE_BITS = 48
PHASE_MASK = (1 << 48) - 1

# the Q14 sine table (one shared definition — the Rust port embeds identical values)
TABLE = [round(math.sin(2 * math.pi * k / TABLE_N) * (1 << 14)) for k in range(TABLE_N)]


def table_at(idx, frac_q14):
    """integer linear interpolation, q14 out (spec §4)."""
    a = TABLE[idx % TABLE_N]
    b = TABLE[(idx + 1) % TABLE_N]
    return a + ((b - a) * frac_q14 >> 14)


def eval_q14(phase48):
    idx = (phase48 * TABLE_N) >> PHASE_BITS
    frac_q14 = ((phase48 & PHASE_MASK) * TABLE_N) >> PHASE_BITS
    return table_at(idx, frac_q14)


def step_u48(freq_mhz, rate):
    """round(freq_mHz * 2^48 / (rate*1000)), INTEGER, half-up (normative)."""
    num = freq_mhz << PHASE_BITS
    den = rate * 1000
    return (num + den // 2) // den


def phase_at(phase0_q16, freq_mhz, rate, i):
    p0 = (phase0_q16 << 32) & PHASE_MASK  # Q16 -> 48-bit (exact: <<32)
    step = step_u48(freq_mhz, rate)
    return (p0 + step * i) & PHASE_MASK


def out_q(phase0_q16, freq_mhz, rate, i, amplitude_q15,
          mod_phase_q16=0, mod_freq_mhz=0, mod_depth_q16=0, coupled_phase48=None):
    """One stream's PCM sample (i64, pre-clamp). All integer."""
    v = eval_q14(phase_at(phase0_q16, freq_mhz, rate, i))
    if mod_depth_q16 and coupled_phase48 is None:
        env_q15 = (1 << 15) + ((mod_depth_q16 * eval_q14(
            phase_at(mod_phase_q16, mod_freq_mhz, rate, i))) >> 15)
    elif mod_depth_q16 and coupled_phase48 is not None:
        env_q15 = (1 << 15) + ((mod_depth_q16 * eval_q14(coupled_phase48)) >> 15)
    else:
        env_q15 = 1 << 15
    return (amplitude_q15 * v * env_q15) >> 29


def clamp_i16(val):
    return max(-32768, min(32767, val))


# --------------------------------------------------------------- vectors ---

CASES = []


def case(name, rate, carrier_mhz, carrier_phase_q16, amp_q15, mod=None,
         coupling=None, indices=None):
    CASES.append(dict(name=name, rate=rate, carrier_mhz=carrier_mhz,
                      carrier_phase_q16=carrier_phase_q16, amp_q15=amp_q15,
                      mod=mod or dict(mod_phase_q16=0, mod_freq_mhz=0,
                                      mod_depth_q16=0),
                      coupling=coupling, indices=indices or (
                          [0, 1, 2, 3, 5, 17, 255, 256, 257,
                           65535, 65536, 65537, 1_000_000, 4_294_967_295]
                      )))


def build_cases():
    # boundary frequencies, rates and depths (spec §5 legal extremes)
    case("gamma40_48k", 48000, 40000, 0, 24576,
         mod=dict(mod_phase_q16=0, mod_freq_mhz=5859, mod_depth_q16=32768))
    case("gamma40_44k1", 44100, 40000, 16384, 24576,
         mod=dict(mod_phase_q16=24576, mod_freq_mhz=6000, mod_depth_q16=49152),
         indices=[0, 1, 2, 11035, 11036, 100000, 1000000])
    case("theta6_48k_max_depth", 48000, 6000, 32768, 8192,
         mod=dict(mod_phase_q16=0, mod_freq_mhz=586, mod_depth_q16=65535))
    case("min_freq_500mhz", 8000, 500, 0, 32767,
         indices=[0, 1, 2, 4095, 4096, 4097])
    case("max_freq_20k", 192000, 20000000, 0, 16384,
         indices=[0, 1, 2, 3, 4, 5, 191, 192, 193])
    case("zero_depth", 48000, 40320, 12345, 32767,
         mod=dict(mod_phase_q16=0, mod_freq_mhz=0, mod_depth_q16=0))
    case("phase_wrap", 48000, 40000, 65535, 16384,
         mod=dict(mod_phase_q16=65535, mod_freq_mhz=5859, mod_depth_q16=32768))
    case("coupled_stereo", 48000, 40000, 0, 12288,
         mod=dict(mod_phase_q16=0, mod_freq_mhz=5859, mod_depth_q16=32768),
         indices=[0, 7, 7777, 24000, 48000])
    case("long_span", 48000, 40000, 8192, 24576,
         mod=dict(mod_phase_q16=16384, mod_freq_mhz=1000, mod_depth_q16=16384),
         indices=[0, 1, 2_147_483_647, 2_147_483_648, 4_294_967_295])
    # coupling: the coupled stream's theta phase = the master's (stream 1)
    case("coupled_slave", 48000, 40040, 21845, 12288,
         mod=dict(mod_phase_q16=0, mod_freq_mhz=0, mod_depth_q16=32768),
         coupling=dict(master_theta=dict(carrier_mhz=5859, phase0_q16=0)),
         indices=[0, 1, 1000, 100000])


def emit_rust():
    lines = [
        "// GENERATED by scripts/neuro/aux_reference.py --vectors (do not edit).",
        "// The Python reference's integer contract; the Rust renderer must",
        "// reproduce every value bit-for-bit.",
        "pub(crate) struct ParityCase {",
        "    pub(crate) name: &'static str,",
        "    pub(crate) rate: u32,",
        "    pub(crate) carrier_mhz: u32,",
        "    pub(crate) carrier_phase_q16: u16,",
        "    pub(crate) amp_q15: u16,",
        "    pub(crate) mod_phase_q16: u16,",
        "    pub(crate) mod_freq_mhz: u32,",
        "    pub(crate) mod_depth_q16: u16,",
        "    /// Some(master theta spec) when the case renders a coupled slave",
        "    pub(crate) coupled_master: Option<(&'static str, u32, u16)>,",
        "    pub(crate) indices: &'static [u64],",
        "    pub(crate) expected: &'static [i64],",
        "}",
        "",
        "pub(crate) static PARITY_CASES: &[ParityCase] = &[",
    ]
    for c in CASES:
        outs = []
        for idx in c["indices"]:
            coupled = None
            if c["coupling"]:
                m = c["coupling"]["master_theta"]
                coupled = phase_at(m["phase0_q16"], m["carrier_mhz"], c["rate"], idx)
            v = out_q(
                c["carrier_phase_q16"], c["carrier_mhz"], c["rate"], idx,
                c["amp_q15"],
                c["mod"]["mod_phase_q16"], c["mod"]["mod_freq_mhz"],
                c["mod"]["mod_depth_q16"], coupled,
            )
            outs.append(v)
        cm = "None"
        if c["coupling"]:
            m = c["coupling"]["master_theta"]
            cm = (f'Some(("master", {m["carrier_mhz"]}, {m["phase0_q16"]}))')
        idxs = ", ".join(str(i) for i in c["indices"])
        vals = ", ".join(str(v) for v in outs)
        lines.append("    ParityCase {")
        lines.append(f'        name: "{c["name"]}",')
        lines.append(f'        rate: {c["rate"]},')
        lines.append(f'        carrier_mhz: {c["carrier_mhz"]},')
        lines.append(f'        carrier_phase_q16: {c["carrier_phase_q16"]},')
        lines.append(f'        amp_q15: {c["amp_q15"]},')
        lines.append(f'        mod_phase_q16: {c["mod"]["mod_phase_q16"]},')
        lines.append(f'        mod_freq_mhz: {c["mod"]["mod_freq_mhz"]},')
        lines.append(f'        mod_depth_q16: {c["mod"]["mod_depth_q16"]},')
        lines.append(f'        coupled_master: {cm},')
        lines.append(f'        indices: &[{idxs}],')
        lines.append(f'        expected: &[{vals}],')
        lines.append("    },")
    lines.append("];")
    lines.append("")
    # the shared Q14 sine table (the single normative definition)
    lines.append("pub(crate) static AUX_TABLE14: [i16; 16384] = [")
    for chunk_start in range(0, TABLE_N, 16):
        row = ", ".join(str(v) for v in TABLE[chunk_start:chunk_start + 16])
        lines.append(f"    {row},")
    lines.append("];")
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--vectors", action="store_true")
    ap.add_argument("--selfcheck", action="store_true")
    a = ap.parse_args()
    build_cases()
    if a.selfcheck or not a.vectors:
        # the reference's own sanity: a 0.5-depth AM of a bin-aligned carrier
        # must show the declared envelope; the max |out| must equal
        # amp*(1+depth) scaled to Q-shifts
        rate = 48000
        peak = max(
            abs(out_q(0, 40000, rate, i, 24576, 0, 5859, 32768))
            for i in range(0, 24000)
        )
        want_max = (24576 * (1 << 14) * ((1 << 15) + 32768 >> 0)) >> 29
        # peak = amp * 1.0 * (1 + 0.5) = amp*1.5: (24576*16384*49152)>>29
        explicit = (24576 * (1 << 14) * 49152) >> 29
        # the Q14 table + integer interpolation quantize the peak by
        # ~(nominal x 2pi/2 / 2^14 + the envelope's own table error)
        tol = explicit * 2 // 8192 + 6
        assert abs(peak - explicit) <= tol, (peak, explicit, tol)
        print(f"reference selfcheck OK: peak {peak} vs {explicit} nominal "
              f"(table-quantization tol {tol})")
    if a.vectors:
        print(emit_rust())
